// src/styles.css is the one source of the loader's look. This turns it into a string module the
// React component and the web component inject, so no bundler CSS loader is needed in any app.
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../src/styles.css", import.meta.url), "utf8")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/\s+/g, " ")
  .replace(/\s*([{}:;,>])\s*/g, "$1")
  .replace(/;}/g, "}")
  .trim();

writeFileSync(
  new URL("../src/css.generated.ts", import.meta.url),
  `// Generated by scripts/gen-css.mjs from src/styles.css. Do not edit.\nexport default ${JSON.stringify(css)};\n`,
);
